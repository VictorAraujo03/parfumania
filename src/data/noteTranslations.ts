const cap = (s: string) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : s);

export function translateNote(note: string): string {
  const t = note.trim();
  return NOTE_PT[t.toLowerCase()] ?? cap(t);
}

export function translateAccord(accord: string): string {
  const t = accord.trim();
  return ACCORD_PT[t.toLowerCase()] ?? cap(t);
}
